def fmt_run(run, east="SimSun", size=11, bold=False, ascii_f="Times New Roman"):
    run.font.name = ascii_f
    run.font.size = Pt(size)
    run.font.bold = bold
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.get_or_add_rFonts()
    rFonts.set(qn("w:eastAsia"), east)


def para(doc, text, size=11, bold=False, east="SimSun", ascii_f="Times New Roman",
         align=None, indent=True, before=0, after=6, line=1.5, lead=None):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.line_spacing = line
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    if align is not None:
        p.alignment = align
    if indent:
        pf.first_line_indent = Pt(size * 2)
    if lead:
        r0 = p.add_run(lead)
        fmt_run(r0, east, size, True, ascii_f)
    r = p.add_run(text)
    fmt_run(r, east, size, bold, ascii_f)
    return p


def h1(doc, text):
    return para(doc, text, size=16, bold=True, east="SimHei", ascii_f="SimHei",
                indent=False, before=14, after=8, line=1.5)


def h2(doc, text):
    return para(doc, text, size=13, bold=True, east="SimHei", ascii_f="SimHei",
                indent=False, before=10, after=6, line=1.5)


def caption(doc, text):
    return para(doc, text, size=11, bold=True, indent=False, before=6, after=3, line=1.3)


def note(doc, text):
    return para(doc, text, size=10.5, bold=False, indent=False, before=2, after=8, line=1.3)


def set_cell(cell, text, bold=False, size=11, align="left"):
    p = cell.paragraphs[0]
    pf = p.paragraph_format
    pf.line_spacing = 1.15
    pf.space_before = Pt(2)
    pf.space_after = Pt(2)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER if align == "center" else WD_ALIGN_PARAGRAPH.LEFT
    r = p.add_run(text)
    fmt_run(r, "SimSun", size, bold)


def add_table(doc, headers, rows, note_text=None, first_col_left=True):
    t = doc.add_table(rows=1 + len(rows), cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j, h in enumerate(headers):
        set_cell(t.cell(0, j), h, bold=True, align="center")
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            al = "left" if (j == 0 and first_col_left) else "center"
            set_cell(t.cell(i + 1, j), val, align=al)
    if note_text:
        note(doc, note_text)
    return t


